// Saloon / Bar generation and drawing — plan-driven (v31)
//
// Recreates the interior + exterior of a Western Saloon / Bar based on the
// Hyper3D Rodin reference model "Old Western saloon", using only the existing
// ctx.pb() renderer (no GLB / Three.js).
//
// v31 changes:
//   - False front is now a PARAPET above the flat roof (not a full-height
//     slab), so the front door + windows on the regular front wall are no
//     longer covered / clipped.
//   - Front windows sit on the regular front wall surface (z1+WALL_T/2),
//     not pushed into the false front.
//   - Added named interior props: Spittoon, WantedPoster01/02, SaloonPainting,
//     AntlerMount, CardDeck, PokerChips, PokerTableCloth, WhiskeyBottle,
//     BeerBarrel, BarTowel, WallSconce01/02.
//   - Added an upright Piano (from piano.js) against the west wall, with a
//     PianoStool.
//   - Code moved into src/game/bar/ folder.
//
// All coords are derived from the TOWN.saloon bounding box. A clear visitor
// path runs along x = b.x = -28.5 from the front door (z = z1) straight north
// to the bar counter (z ≈ -9.7). Tables sit either side of this path; stools
// sit in front of the counter; shelves sit on the back wall behind the bar.

