// Helper: get the front (south, +z) edge z of the BarCounter for placing the
// BarTowel on the customer-facing edge.
function sz_edge(o){
  return o.size[2]/2 - 0.03;
}

// ---------------------------------------------------------------------------
// drawSaloonExterior — false-front PARAPET (above the flat roof only),
// SALOON sign, porch posts, porch roof, front windows on the regular front
// wall, porch railing, and chimney.
//
// v31 fix: the false front is now a PARAPET that sits ON TOP of the front
// wall (from y=top to y=ffTop), NOT a full-height slab. This means the front
// door + windows on the regular front wall are fully visible and the door
// is no longer "stuck inside the wall".
// ---------------------------------------------------------------------------
function drawSaloonExterior(ctx, P){
  const {b, x0, x1, z0, z1, gy, top} = P;
  const WT=WALL_T;
  const wd=C.wood, dk=C.dark, w2=C.wood2, pal=C.pale, stn=C.stone, gold=C.gold;

  // ---- FALSE FRONT PARAPET ----
  // A tall flat wall sitting ON TOP of the front wall, rising above the flat
  // roof. From y=top (wall top) to y=ffTop (parapet top). Full width of the
  // building + a bit. This gives the classic tall rectangular western
  // saloon silhouette WITHOUT covering the door or windows.
  const ffTop=gy+b.h+2.6;          // parapet top
  const ffH=ffTop-top;              // parapet height (~2.6m above the roof)
  const ffW=b.w+0.6;                // slightly wider than the building
  const ffX=(x0+x1)/2;
  const ffZ=z1;                     // at the front wall
  const ffT=WALL_T+.06;             // a bit thicker than the walls
  // Parapet main slab (centred at top + ffH/2).
  ctx.pb(ffX, top+ffH/2, ffZ, ffW, ffH, ffT, pal);
  // Parapet cornice — a slightly wider trim at the very top.
  ctx.pb(ffX, ffTop+.08, ffZ, ffW+.30, .16, ffT+.20, dk);
  // Decorative band just below the cornice.
  ctx.pb(ffX, ffTop-.18, ffZ, ffW+.06, .12, ffT+.06, dk);

  // ---- "SALOON" SIGN ----
  // A large horizontal sign board mounted on the FRONT (south, +z) face of
  // the parapet. Gold border + dark inner panel + 6 gold vertical letter
  // slats suggesting "SALOON". The sign is placed at z = ffZ + ffT/2 + offset
  // so it sits PROUD of (south of) the parapet front face — visible from the
  // street, not hidden behind the parapet slab.
  const signY=top+0.9;
  const signW=b.w-1.5;
  const signH=1.00;
  const signT=0.16;
  const signZ=ffZ+ffT/2+0.20;      // 0.20m proud of the parapet front face (south)
  // Sign border frame (gold).
  ctx.pb(ffX, signY, signZ, signW+.30, signH+.30, signT, gold);
  // Sign inner panel (dark wood) — slightly south of the frame so it's
  // visible on the front face.
  ctx.pb(ffX, signY, signZ+.08, signW, signH, signT, dk);
  // ---- "BAR" letters (gold, 3D pixel-style) ----
  // Build each letter from small gold boxes on the sign's front face.
  // The sign inner panel front face is at signZ + .08 + signT/2 = signZ+.16.
  // Letters sit PROUD of that face (at signZ + .16 + .06) so they don't
  // z-fight with the panel and are clearly visible.
  const letterColor = gold;
  const letterZ = signZ + .16 + .06;  // proud of the sign panel front face
  const letterH = 0.55;        // letter height
  const letterW = 0.35;        // letter width
  const letterGap = 0.15;      // gap between letters
  const letterDepth = 0.06;    // letter thickness (proud of the panel)
  const totalW = 3*letterW + 2*letterGap;
  const letterStartX = ffX - totalW/2 + letterW/2;
  // Helper to draw a small box for a letter stroke.
  const stroke = (cx, cy, w, h) => {
    ctx.pb(cx, cy, letterZ, w, h, letterDepth, letterColor);
  };
  // Letter heights: top, middle, bottom Y positions.
  const yT = signY + letterH/2;   // top
  const yM = signY;                // middle
  const yB = signY - letterH/2;   // bottom
  const halfW = letterW/2;
  // 'B' — two vertical strokes on the left + two horizontal strokes + middle + bumps on the right
  {
    const bx = letterStartX;
    // Left vertical (full height).
    stroke(bx - halfW + 0.04, signY, 0.08, letterH);
    // Top horizontal.
    stroke(bx, yT - 0.04, letterW - 0.04, 0.08);
    // Middle horizontal.
    stroke(bx, yM, letterW - 0.08, 0.08);
    // Bottom horizontal.
    stroke(bx, yB + 0.04, letterW - 0.04, 0.08);
    // Right bumps (top + bottom halves).
    stroke(bx + halfW - 0.04, yT - letterH/4, 0.08, letterH/2 - 0.04);
    stroke(bx + halfW - 0.04, yB + letterH/4, 0.08, letterH/2 - 0.04);
  }
  // 'A' — two diagonal-ish verticals + a middle bar. Simplified as 2 verticals
  // + top join + middle bar.
  {
    const ax = letterStartX + letterW + letterGap;
    // Left vertical (slightly inward at top — simplified to vertical).
    stroke(ax - halfW + 0.06, signY, 0.08, letterH);
    // Right vertical.
    stroke(ax + halfW - 0.06, signY, 0.08, letterH);
    // Top join (a horizontal bar at the top).
    stroke(ax, yT - 0.04, letterW - 0.08, 0.08);
    // Middle bar.
    stroke(ax, yM, letterW - 0.10, 0.08);
  }
  // 'R' — left vertical + top horizontal + right bump (top half) + diagonal leg.
  {
    const rx = letterStartX + 2*(letterW + letterGap);
    // Left vertical (full height).
    stroke(rx - halfW + 0.04, signY, 0.08, letterH);
    // Top horizontal.
    stroke(rx, yT - 0.04, letterW - 0.04, 0.08);
    // Middle horizontal (shorter — only the top bowl).
    stroke(rx, yM, letterW - 0.10, 0.08);
    // Right bump (top half only).
    stroke(rx + halfW - 0.04, yT - letterH/4, 0.08, letterH/2 - 0.04);
    // Diagonal leg (a single box going down to the bottom-right).
    stroke(rx + halfW - 0.10, yB + letterH/4, 0.08, letterH/2 - 0.04);
  }
  // Hanging brackets (going back to the parapet).
  ctx.pb(ffX-signW/2+.15, signY+signH/2+.10, (ffZ+signZ)/2, .10, .20, (signZ-ffZ), dk);
  ctx.pb(ffX+signW/2-.15, signY+signH/2+.10, (ffZ+signZ)/2, .10, .20, (signZ-ffZ), dk);

  // ---- FRONT PORCH POSTS ----
  const porchDepth=1.6;
  const porchZ=z1+porchDepth/2;
  const postZ=z1+porchDepth-.10;
  const postH=gy+2.6;
  const postCy=postH/2;
  const postXs=[x0+0.4, b.x-2.4, b.x+2.4, x1-0.4];
  for(const px of postXs){
    ctx.pb(px, postCy, postZ, .22, postH, .22, dk);
    ctx.pb(px, gy+.06, postZ, .34, .12, .34, stn);
    ctx.pb(px, postH+.06, postZ, .28, .10, .28, wd);
  }

  // ---- PORCH ROOF OVERHANG ----
  const porchRoofY=gy+2.75;
  const porchRoofW=b.w+.8;
  const porchRoofD=porchDepth+.4;
  ctx.pb((x0+x1)/2, porchRoofY, porchZ, porchRoofW, .12, porchRoofD, dk);
  ctx.pb((x0+x1)/2, porchRoofY-.18, postZ, porchRoofW, .24, .06, w2);

  // ---- FRONT WINDOWS (on the regular front wall, NOT in the false front) ----
  // These sit at z1+WALL_T/2 (the outer face of the regular front wall), well
  // below the parapet (which starts at y=top). The door gap is centred at
  // b.x, so we place windows at b.x ± b.w/4 — clear of the door.
  const winYExt=gy+1.5;
  const winWext=1.6, winHext=1.8;
  for(const wx of [b.x-b.w/4, b.x+b.w/4]){
    // Window frame (raised wood border on the outer face of the front wall).
    ctx.pb(wx, winYExt, z1+WALL_T/2+.02, winWext+.16, winHext+.16, .06, pal);
    // Glass pane (dark, on the wall face).
    ctx.pb(wx, winYExt, z1+WALL_T/2, winWext, winHext, .04, [0.13,0.18,0.22]);
    // Cross bars dividing the pane into 4.
    ctx.pb(wx, winYExt, z1+WALL_T/2+.02, winWext, .06, .05, pal);
    ctx.pb(wx, winYExt, z1+WALL_T/2+.02, .06, winHext, .05, pal);
    // Shutters on the outer side of each window.
    const shX=wx> b.x ? wx+winWext/2+.18 : wx-winWext/2-.18;
    ctx.pb(shX, winYExt, z1+WALL_T/2+.10, .14, winHext, .08, dk);
    for(const sy of [winYExt-winHext/3, winYExt, winYExt+winHext/3]){
      ctx.pb(shX, sy, z1+WALL_T/2+.14, .16, .04, .04, w2);
    }
  }

  // ---- PORCH RAILING ----
  // v32: REMOVED. The railing ran across the porch edge and visually
  // appeared as a brown horizontal bar blocking the door when entering /
  // exiting. The 4 porch posts alone are enough for the western look.
  // (The rail + balusters are removed to keep the entrance fully clear.)

  // ---- CHIMNEY ----
  const chimX=x1-1.5, chimZ=z0+2.0;
  const chimBase=top, chimTop=top+2.2;
  const brick=[0.62,0.30,0.22];
  ctx.pb(chimX, (chimBase+chimTop)/2, chimZ, .54, chimTop-chimBase, .54, brick);
  ctx.pb(chimX, chimTop+.10, chimZ, .66, .20, .66, dk);
  ctx.pb(chimX, chimBase+.08, chimZ, .70, .16, .70, dk);
  for(const cy of [chimBase+.5, chimBase+1.1, chimBase+1.7]){
    ctx.pb(chimX, cy, chimZ+.28, .56, .04, .04, dk);
  }
}
