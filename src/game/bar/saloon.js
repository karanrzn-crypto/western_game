// ---------------------------------------------------------------------------
// saloonPlan — single source of truth for all saloon coordinates.
// ---------------------------------------------------------------------------
export function saloonPlan(){
  const b=TOWN.saloon;
  const x0=b.x-b.w/2, x1=b.x+b.w/2;        // west / east walls
  const z0=b.z-b.d/2, z1=b.z+b.d/2;        // north (back) / south (front)
  const gy=0;                               // ground at the saloon (flat town)
  const top=gy+b.h;                         // ceiling / roof height
  const frontZ=b.z<0 ? z1 : z0;             // front wall = south (z1)
  const backZ=b.z<0 ? z0 : z1;              // back wall = north (z0)
  const doorX=b.x;                          // door centred on facade
  const gapL=doorX-DOOR_GAP/2, gapR=doorX+DOOR_GAP/2;
  return { b, x0, x1, z0, z1, gy, top, frontZ, backZ, doorX, gapL, gapR };
}

// ---------------------------------------------------------------------------
// generateSaloon — player colliders + camera colliders.
// The building shell (walls + door + floor + shell camBoxes) is generated by
// generateTown in town-buildings.js. We add the INTERIOR furniture colliders
// and the EXTERIOR feature colliders (false front parapet, porch posts,
// chimney) here.
// ---------------------------------------------------------------------------
export function generateSaloon(ctx){
  const P=saloonPlan();
  const {b, x0, x1, z0, z1, top, frontZ, backZ} = P;
  const WT=WALL_T;

  // ---- Interior furniture colliders (player obstacles) ----
  const bc=(cx0,cz0,cx1,cz1)=>ctx.boxCol(cx0,cz0,cx1,cz1);
  const t=.12;

  // [BarCounter] — solid block collider.
  {
    const o=SALOON_LAYOUT.BarCounter;
    const [cx, , cz]=o.center, [sx, , sz]=o.size;
    bc(cx-sx/2, cz-sz/2, cx+sx/2, cz+sz/2);
  }
  // [SaloonTable01] and [SaloonTable02] — thin collider.
  for(const key of ['SaloonTable01','SaloonTable02']){
    const o=SALOON_LAYOUT[key];
    const [cx, , cz]=o.center, [sx, , sz]=o.size;
    bc(cx-sx/2+t, cz-sz/2+t, cx+sx/2-t, cz+sz/2-t);
  }
  // [Piano] — solid block against the west wall (so the player can't walk
  // through it). The piano's BACK is flush against the west wall (x=x0+WT),
  // the body extends INTO the room (east, +x) by 0.65m, and the keyboard
  // faces east. This avoids the v31 bug where the piano was placed with its
  // depth axis along X (into the wall) — half of it was inside the wall.
  if(SALOON_INCLUDE_PIANO){
    const pd=0.65, pw=1.50;
    // Piano back at x = x0 + WT (on the west wall surface).
    const pBackX=x0+WT;
    // Piano centre is pd/2 INTO the room (east of the wall).
    const pCentreX=pBackX+pd/2;
    // Piano z-centre: near the front of the room, against the west wall.
    const pCentreZ=z1-1.8;
    // Player collider: from the wall to pCentreX + pd/2, spanning the piano width.
    bc(pBackX, pCentreZ-pw/2, pCentreX+pd/2, pCentreZ+pw/2);
  }

  // ---- Camera colliders ----
  const cam=(cx0,cz0,cx1,cz1,ch,cy0=0)=>ctx.cam(cx0,cz0,cx1,cz1,ch,cy0);
  // [BarCounter] camera box.
  {
    const o=SALOON_LAYOUT.BarCounter;
    const [cx, , cz]=o.center, [sx, sy, sz]=o.size;
    cam(cx-sx/2-t, cz-sz/2-t, cx+sx/2+t, cz+sz/2+t, P.gy+sy+.05);
  }

  // ---- Exterior camera colliders ----
  // v33: reduced to only the 2 large exterior features that the camera
  // would actually clip through (the false front parapet and the porch roof
  // overhang). The 4 porch posts and the chimney are small / thin enough
  // that removing their camBoxes doesn't cause visible clipping but does
  // reduce the per-frame camera-collision work (helps FPS).
  const ffTop=P.gy+b.h+2.6+.2;
  // False front parapet (above the flat roof only).
  cam(x0-.1, z1-WALL_T/2-.05, x1+.1, z1+WALL_T/2+.05, ffTop, P.gy+b.h-.02);
  // Porch roof overhang camera box.
  const porchDepth=1.6;
  cam(x0-.4, z1-.1, x1+.4, z1+porchDepth+.3, P.gy+2.85, P.gy+2.6);

  // v54: floor prop colliders (from interior.js, simple version)
  buildSaloonColliders(ctx);
}

// ---------------------------------------------------------------------------
// drawSaloon (v51) — interiors are now baked via buildSaloonInterior (see
// interior.js). The only thing drawn per-frame here is the exterior shell
// (false front, sign, porch) via drawSaloonExterior.
// ---------------------------------------------------------------------------
export function drawSaloon(ctx){ drawSaloonExterior(ctx, saloonPlan()); }

// ---------------------------------------------------------------------------
// drawSaloonBuilding — v40: draws the FULL saloon building exterior (walls +
// flat roof + bat-wing doors) directly, NOT through bldWithDoor. This
// avoids the dark-gap bug where bldWithDoor left an empty doorway that hid
// the bat-wing doors.
//
// The bat-wing doors are drawn RIGHT IN the door gap, so they're always
// visible (no dark rectangle hiding them). The door state (open/closed) is
// read from the saloon door object in ctx.doors.
// ---------------------------------------------------------------------------
export function drawSaloonBuilding(ctx){
  const P=saloonPlan();
  const {b, x0, x1, z0, z1, gy, top, doorX, gapL, gapR, frontZ, backZ} = P;
  const WT=WALL_T;
  const wd=C.wood, dk=C.dark, pal=C.pale;

  // ---- 4 EXTERIOR WALLS ----
  // Front wall: split around the door gap BELOW, with a wall section ABOVE
  // the door (from the door top to the roof). v43: the wall above the door
  // was missing, creating a dark void above the doorway.
  const H=b.h+.03, cy=gy+H/2;
  ctx.pb((x0+gapL)/2, cy, frontZ, gapL-x0, H, WT, wd);   // front-left
  ctx.pb((gapR+x1)/2, cy, frontZ, x1-gapR, H, WT, wd);    // front-right
  // Wall section ABOVE the door (from door top to roof). This closes the
  // gap above the doorway so the wall is continuous.
  const doorTopY = gy + DOOR_H;   // top of the door opening
  const aboveH = top - doorTopY; // height of the wall section above the door
  if(aboveH > 0.02){
    const aboveCy = doorTopY + aboveH/2;
    ctx.pb(doorX, aboveCy, frontZ, DOOR_GAP, aboveH, WT, wd);
  }
  // West wall (full depth).
  ctx.pb(x0+WT/2, cy, (z0+z1)/2, WT, H, z1-z0, wd);
  // East wall (full depth).
  ctx.pb(x1-WT/2, cy, (z0+z1)/2, WT, H, z1-z0, wd);
  // Back wall (full width).
  ctx.pb((x0+x1)/2, cy, backZ, b.w, H, WT, wd);

  // ---- FLAT ROOF ----
  ctx.pb((x0+x1)/2, top+.01, (z0+z1)/2, b.w+.06, .06, b.d+.06, dk);

  // ---- BAT-WING DOORS (drawn by drawBatwingDoors from bar/batwing.js) ----
  // v46: the saloon door object is created in generateSaloonShell. Find it
  // and draw the bat-wing doors (everything rotates as a rigid body).
  const sd = ctx.doors.find(x => x.key === 'saloon');
  if (sd) drawBatwingDoors(ctx, sd, gy);

  // ---- FALSE FRONT PARAPET + SALOON SIGN + PORCH (the old drawSaloonExterior) ----
  drawSaloonExterior(ctx, P);
}

